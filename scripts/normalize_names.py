"""
One-off: clean trailing latin-letter suffixes (반/조 codes like 'B', 'F', 'H') and
trailing parenthesized comments from authors.name.

Read the live D1 state, compute the cleaned name for each row, and emit UPDATE
statements only for the rows that actually change.
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

NAME_TRAILING_PARENS = re.compile(r"\s*\([^)]*\)\s*$")
NAME_TRAILING_LATIN  = re.compile(r"[A-Za-z]+$")


def normalize_name(raw: str) -> str:
    n = (raw or "").strip()
    # apply both rules until neither matches — handles e.g. "김민준B(보충)" → "김민준"
    while True:
        before = n
        n = NAME_TRAILING_PARENS.sub("", n).strip()
        n = NAME_TRAILING_LATIN.sub("", n).strip()
        if n == before:
            return n


def fetch_authors() -> list[tuple[str, str]]:
    proc = subprocess.run(
        [
            "npx", "wrangler", "d1", "execute", "DB", "--remote", "--json",
            "--command", "SELECT id, name FROM authors WHERE name LIKE '%(%' OR name GLOB '*[A-Za-z]*';",
        ],
        check=True, capture_output=True, text=True,
    )
    start = proc.stdout.find("[")
    payload = json.loads(proc.stdout[start:])
    out: list[tuple[str, str]] = []
    for batch in payload:
        for row in batch.get("results", []):
            out.append((row["id"], row["name"]))
    return out


def sql_str(v: str) -> str:
    return "'" + v.replace("'", "''") + "'"


def main():
    rows = fetch_authors()
    changes: list[tuple[str, str, str]] = []
    for aid, raw in rows:
        cleaned = normalize_name(raw)
        if cleaned and cleaned != raw:
            changes.append((aid, raw, cleaned))

    print(f"Matched {len(rows)} candidate rows; {len(changes)} need a rename.", file=sys.stderr)
    for aid, raw, cleaned in changes:
        print(f"  {raw!r:50s} -> {cleaned!r}", file=sys.stderr)

    out_path = Path("out/normalize_names.sql")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    sql = [
        "-- Generated by scripts/normalize_names.py — strip trailing 'B'/'F'/(...) suffixes from authors.name.",
        "-- D1 rejects explicit BEGIN/COMMIT; each statement runs autocommit.",
        "",
    ]
    for aid, raw, cleaned in changes:
        sql.append(
            f"UPDATE authors SET name = {sql_str(cleaned)}, updated_at = CURRENT_TIMESTAMP "
            f"WHERE id = {sql_str(aid)}; -- was {raw!r}"
        )
    out_path.write_text("\n".join(sql) + "\n", encoding="utf-8")
    print(f"\nWrote {out_path} ({len(changes)} UPDATEs).", file=sys.stderr)


if __name__ == "__main__":
    main()
