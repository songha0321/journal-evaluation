#!/usr/bin/env python3
"""파싱된 게재 꼭지 → D1 articles 적재 SQL 생성 (migration 0012 적용 후 사용).

  1) 백필: 기존 402행에 content_hash·part_no 등을 채운다(1회).
       python3 scripts/load_articles.py backfill -o out/backfill_articles.sql
  2) 적재: parse_final_docx.py 결과를 SQL로 만든다.
       python3 scripts/load_articles.py load out/articles_parsed.json \
              -o out/load_articles.sql [--project '2027 항해일지']

둘 다 SQL만 만든다. 실제 반영은 검토 후:
  npx wrangler d1 execute sdij-journal --remote --file out/load_articles.sql

적재 규칙
  - author_id는 (기수, 정규화 이름)으로 매칭한다. 동명이인은 관/반으로 가른다.
    끝내 못 가르면 적재하지 않고 리포트에 남긴다(추측 적재 금지).
  - authors.cohort는 CHECK(cohort >= 5)라 3·4기(2021·2022 항해일지)는 애초에
    적재할 수 없다. 사용자 결정대로 제외한다.
  - 이미 있는 행과 content_hash가 같으면 INSERT 대신 UPDATE로 메타데이터만 보강한다
    (comment·관/반·호차는 기존 402행에 없던 정보다).
  - (source_file, source_order) UNIQUE 위에서 UPSERT하므로 몇 번 돌려도 안전하다.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
import unicodedata as ud
from collections import defaultdict
from pathlib import Path

DB = "sdij-journal"

_PARENS = re.compile(r"\s*\([^)]*\)\s*$")
_LATIN = re.compile(r"[A-Za-z]+$")


def nn(x: str) -> str:
    """이름 정규화 — NFC + 괄호/라틴 접미 제거 + 공백 제거. 기존 ETL과 같은 규칙."""
    x = ud.normalize("NFC", str(x or "")).strip()
    while True:
        b = x
        x = _PARENS.sub("", x).strip()
        x = _LATIN.sub("", x).strip()
        if x == b:
            break
    return x.replace(" ", "")


def content_hash(body: str) -> str:
    return hashlib.sha1(re.sub(r"[\s\W_]+", "", ud.normalize("NFC", body)).encode()).hexdigest()


def esc(s) -> str:
    return str(s).replace("'", "''")


def lit(v) -> str:
    if v is None or v == "":
        return "NULL"
    if isinstance(v, int):
        return str(v)
    return "'" + esc(v) + "'"


def d1(sql: str) -> list[dict]:
    proc = subprocess.run(
        ["npx", "wrangler", "d1", "execute", DB, "--remote", "--json", "--command", sql],
        check=True, capture_output=True, text=True,
    )
    payload = json.loads(proc.stdout[proc.stdout.index("["):])
    rows: list[dict] = []
    for batch in payload:
        rows.extend(batch.get("results", []))
    return rows


# ── title 파싱 (기존 402행 백필용) ────────────────────────────────────────
# 'Part 1. Chapter 1. 10월의 여러분에게 - 시험을 잘 보는 완벽한 방법'
# 'Part2-1. 1년 공부몰입도'  'Part 3. 부엉이를 위한 항해지도 (#TA)'

def split_title(title: str) -> dict:
    t = ud.normalize("NFC", title or "").strip()
    out = {"part_no": None, "chapter_no": None, "part_title": None, "subtitle": None}
    m = re.match(r"^Part\s*(\d+)(?:\s*-\s*(\d+))?\s*[.．]?\s*(.*)$", t, re.I)
    if not m:
        out["part_title"] = t or None
        return out
    out["part_no"] = int(m.group(1))
    if m.group(2):
        out["chapter_no"] = int(m.group(2))
    rest = m.group(3).strip()
    mc = re.match(r"^Chapter\s*(\d+)\s*[.．]?\s*(.*)$", rest, re.I)
    if mc:
        out["chapter_no"] = int(mc.group(1))
        rest = mc.group(2).strip()
    # '목차명 - 소제목' 또는 '목차명 (#태그)'
    mt = re.match(r"^(.*?)\s+\((#.*)\)$", rest)
    if mt:
        out["part_title"], out["subtitle"] = mt.group(1).strip() or None, mt.group(2).strip()
        return out
    if " - " in rest:
        head, tail = rest.split(" - ", 1)
        out["part_title"], out["subtitle"] = head.strip() or None, tail.strip() or None
        return out
    out["part_title"] = rest or None
    return out


def cmd_backfill(args) -> int:
    rows = d1("SELECT id, title, final_content FROM articles ORDER BY created_at, id")
    print(f"기존 articles {len(rows)}행 조회", file=sys.stderr)
    sql = [
        "-- Generated by scripts/load_articles.py backfill",
        "-- 기존 게재 원고에 content_hash·Part 구조를 채운다. migration 0012 적용 후 실행.",
        "",
    ]
    for r in rows:
        body = r.get("final_content") or ""
        parts = split_title(r.get("title") or "")
        sets = [
            f"content_hash = {lit(content_hash(body))}",
            f"char_count = {len(re.sub(r'\s', '', body))}",
            f"part_no = {lit(parts['part_no'])}",
            f"chapter_no = {lit(parts['chapter_no'])}",
            f"part_title = {lit(parts['part_title'])}",
            f"subtitle = {lit(parts['subtitle'])}",
        ]
        sql.append(f"UPDATE articles SET {', '.join(sets)} WHERE id = {lit(r['id'])};")
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(sql) + "\n", encoding="utf-8")
    print(f"{out} 생성 ({len(rows)} UPDATE)", file=sys.stderr)
    return 0


# ── 적재 ──────────────────────────────────────────────────────────────────

def parse_issue(label: str | None, default_project: str) -> tuple[str, str] | None:
    """'2027 항해일지 2호차' → ('2027 항해일지', '2호차')."""
    if not label:
        return None
    m = re.match(r"^(?:(\d{4})\s*항해일지)?\s*.*?(\d+)\s*호차?$", ud.normalize("NFC", label))
    if not m:
        return None
    project = f"{m.group(1)} 항해일지" if m.group(1) else default_project
    return project, f"{m.group(2)}호차"


def cmd_load(args) -> int:
    pieces = json.loads(Path(args.parsed).read_text())
    pieces = [p for p in pieces if p.get("body")]
    print(f"파싱 결과 {len(pieces)} 꼭지(본문 있는 것만)", file=sys.stderr)

    authors = d1("SELECT id, name, cohort, student_type, hall, class_name FROM authors")
    by_key: dict[tuple, list[dict]] = defaultdict(list)
    for a in authors:
        by_key[(a["cohort"], nn(a["name"]))].append(a)

    # 0012 적용 전에도 리포트를 볼 수 있게, 있는 컬럼만 조회한다.
    cols_present = {c["name"] for c in d1("PRAGMA table_info(articles)")}
    if "content_hash" not in cols_present:
        print("경고: migration 0012 미적용 — 중복 판정 없이 전부 신규로 계산한다.", file=sys.stderr)
        existing = []
    else:
        existing = d1("SELECT id, author_id, title, content_hash, part_no, part_title,"
                      " source_type, char_count FROM articles")
    by_hash = defaultdict(list)
    by_piece = defaultdict(list)      # (author_id, part_no, 정규화 part_title)
    for e in existing:
        if e.get("content_hash"):
            by_hash[e["content_hash"]].append(e)
        by_piece[(e["author_id"], e.get("part_no"), nn(e.get("part_title") or ""))].append(e)
    if existing and not any(e.get("content_hash") for e in existing):
        print("경고: 기존 행에 content_hash가 없다. backfill을 먼저 돌려야 중복 판정이 된다.",
              file=sys.stderr)

    # 파싱 결과 쪽에서도 같은 (저자, Part) 조합이 몇 번 나오는지 미리 센다.
    piece_key_count: dict[tuple, int] = defaultdict(int)
    for p in pieces:
        cands = by_key.get((p.get("cohort"), nn(p.get("author_name") or "")), [])
        if len(cands) == 1:
            piece_key_count[(cands[0]["id"], p.get("part_no"),
                             nn(p.get("part_title") or ""))] += 1

    issues: dict[tuple[str, str], None] = {}
    inserts, updates = [], []
    unmatched, ambiguous, replaced = [], [], []
    used: set[str] = set()   # 같은 기존 행을 두 번 갱신하지 않도록

    for p in pieces:
        name, cohort = nn(p.get("author_name") or ""), p.get("cohort")
        cands = by_key.get((cohort, name), [])
        if len(cands) > 1:
            # 동명이인 — 관/반으로 가른다.
            narrowed = [c for c in cands
                        if (p.get("hall") and c.get("hall") == p["hall"])
                        or (p.get("class_name") and c.get("class_name") == p["class_name"])]
            cands = narrowed or cands
        if not cands:
            unmatched.append(p)
            continue
        if len(cands) > 1:
            ambiguous.append((p, cands))
            continue
        author = cands[0]

        iss = parse_issue(p.get("issue_label"), args.project)
        label_full = p.get("issue_label")
        if iss:
            issues[iss] = None
            label_full = f"{iss[0]} {iss[1]}"   # 파일명에 연도가 없어도 issue_id가 붙도록

        title_bits = [b for b in [
            f"Part {p['part_no']}." if p.get("part_no") else None,
            f"Chapter {p['chapter_no']}." if p.get("chapter_no") else None,
            p.get("part_title"),
        ] if b]
        title = " ".join(title_bits)
        if p.get("subtitle"):
            title = f"{title} - {p['subtitle']}" if title else p["subtitle"]

        # 해시가 같아도 저자가 다르면 남의 행이다. 저자 일치까지 확인한다
        # (이 가드가 없으면 다른 학생 행에 메타데이터를 덮어쓴다).
        dup = [e for e in by_hash.get(p["content_hash"], [])
               if e["author_id"] == author["id"]]
        # 해시가 어긋나도 같은 저자·같은 Part면 같은 꼭지의 다른 판본이다.
        # 실제로 기존 402행 중 24건은 comment가 본문 앞에 붙어 있었다(7월 적재분).
        key = (author["id"], p.get("part_no"), nn(p.get("part_title") or ""))
        # 1:1일 때만 '같은 꼭지'로 본다. 한 Part에 같은 저자의 꼭지가 둘 이상이면
        # (예: Part 4 콘텐츠 추천의 과목별 꼭지) 어느 것이 짝인지 알 수 없다.
        # 실제로 이 가드가 없을 때 성우빈의 국어/과탐 꼭지가 서로 뒤바뀌어 덮였다.
        same_piece = ([] if dup or len(by_piece.get(key, [])) != 1
                      or piece_key_count[key] != 1 else by_piece[key])
        cols = {
            "issue_label": label_full,
            "part_no": p.get("part_no"),
            "chapter_no": p.get("chapter_no"),
            "part_title": p.get("part_title"),
            "section": p.get("section"),
            "subtitle": p.get("subtitle"),
            "comment": p.get("comment"),
            "hanmadi": p.get("hanmadi"),
            "focus_json": p.get("focus_json"),
            "author_name": p.get("author_name"),
            "hall": p.get("hall"),
            "class_name": p.get("class_name"),
            "university": p.get("university"),
            "epithet": p.get("epithet"),
            "content_hash": p.get("content_hash"),
            "source_file": p.get("source_file"),
            "source_type": args.source_type,
            "source_order": p.get("source_order"),
            "char_count": p.get("char_count"),
        }
        if dup or same_piece:
            target = next((t for t in (dup or same_piece) if t["id"] not in used), None)
        else:
            target = None
        if target is not None:
            used.add(target["id"])
            fields = dict(cols)
            # 본문 교체는 docx(최종원고)일 때만 한다. 인쇄 PDF·OCR 본문은 줄바꿈에서
            # 공백이 사라지므로, 이미 있는 docx 출처 본문을 덮어쓰면 품질이 떨어진다.
            if same_piece and args.source_type == "docx":
                fields["final_content"] = p["body"]
                fields["title"] = title
                replaced.append((p["author_name"], title,
                                 target.get("char_count"), p["char_count"]))
            sets = ", ".join(f"{k} = {lit(v)}" for k, v in fields.items())
            updates.append(
                f"UPDATE articles SET {sets}, updated_at = CURRENT_TIMESTAMP "
                f"WHERE id = {lit(target['id'])};  -- {esc(p['author_name'])} / {esc(title)}"
            )
            continue

        cols_full = {"author_id": author["id"], "title": title,
                     "final_content": p["body"], "article_status": "final", **cols}
        keys = ", ".join(cols_full)
        vals = ", ".join(lit(v) for v in cols_full.values())
        upd = ", ".join(f"{k} = excluded.{k}" for k in cols_full if k not in ("source_file", "source_order"))
        inserts.append(
            f"INSERT INTO articles ({keys}) VALUES ({vals})\n"
            f"  ON CONFLICT(source_file, source_order) DO UPDATE SET {upd}, updated_at = CURRENT_TIMESTAMP;"
        )

    sql = [
        "-- Generated by scripts/load_articles.py load",
        "-- migration 0012 적용 후 실행. 재실행 안전(UPSERT).",
        "",
        "-- 역대 호차 등록 (없을 때만)",
    ]
    for (project, label) in sorted(issues):
        sql.append(
            f"INSERT OR IGNORE INTO ax_issue (project, issue_label, sort_order, status) "
            f"VALUES ({lit(project)}, {lit(label)}, {int(re.sub(r'\D', '', label) or 0)}, 'published');"
        )
    sql += ["", "-- 신규 게재 원고", *inserts, "", "-- 기존 원고 메타데이터 보강", *updates, ""]
    sql.append("-- issue_id 연결")
    sql.append(
        "UPDATE articles SET issue_id = (SELECT i.id FROM ax_issue i "
        "WHERE i.project || ' ' || i.issue_label = articles.issue_label) "
        "WHERE issue_label IS NOT NULL AND issue_id IS NULL;"
    )

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(sql) + "\n", encoding="utf-8")

    print(f"\n호차 {len(issues)}개 · 신규 INSERT {len(inserts)} · 기존 UPDATE {len(updates)}"
          f" (그중 본문 교체 {len(replaced)})", file=sys.stderr)
    for r in replaced[:10]:
        print(f"  [본문교체] {r[0]} / {r[1][:40]} — {r[2]}자 → {r[3]}자", file=sys.stderr)
    print(f"이름 매칭 실패 {len(unmatched)} · 동명이인 미해결 {len(ambiguous)}", file=sys.stderr)
    for p in unmatched:
        print(f"  [매칭실패] {p['cohort']}기 {p['author_name']} ({p.get('hall')} {p.get('class_name')})"
              f" — {p['source_file']} #{p['source_order']}", file=sys.stderr)
    for p, cs in ambiguous:
        print(f"  [동명이인] {p['cohort']}기 {p['author_name']} → 후보 {len(cs)}명"
              f" — {p['source_file']} #{p['source_order']}", file=sys.stderr)
    print(f"\n{out} 생성", file=sys.stderr)
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("backfill", help="기존 402행에 content_hash·Part 구조 채우기")
    b.add_argument("-o", "--out", default="out/backfill_articles.sql")
    b.set_defaults(func=cmd_backfill)
    l = sub.add_parser("load", help="파싱 결과 적재 SQL 생성")
    l.add_argument("parsed", help="parse_final_docx.py가 만든 JSON")
    l.add_argument("-o", "--out", default="out/load_articles.sql")
    l.add_argument("--project", default="2027 항해일지", help="파일명에 연도가 없을 때 쓸 프로젝트명")
    l.add_argument("--source-type", default="docx", choices=["docx", "pdf", "ocr"],
                   help="본문 출처. docx만 기존 본문을 덮어쓴다.")
    l.set_defaults(func=cmd_load)
    args = ap.parse_args()
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())
